/**
 * WhatsApp Cloud API client.
 *
 * Only the pieces this storefront needs: verifying that an inbound webhook
 * really came from Meta, and sending a few message shapes back.
 */
import { optionalEnv, requireEnv } from "./env.ts";

const GRAPH_VERSION = "v21.0";

export const isWhatsAppConfigured = () =>
  Boolean(optionalEnv("WHATSAPP_PHONE_NUMBER_ID") && optionalEnv("WHATSAPP_ACCESS_TOKEN"));

async function send(payload: Record<string, unknown>): Promise<void> {
  const res = await fetch(
    `https://graph.facebook.com/${GRAPH_VERSION}/${requireEnv("WHATSAPP_PHONE_NUMBER_ID")}/messages`,
    {
      method: "POST",
      headers: {
        authorization: `Bearer ${requireEnv("WHATSAPP_ACCESS_TOKEN")}`,
        "content-type": "application/json",
      },
      body: JSON.stringify({ messaging_product: "whatsapp", ...payload }),
    },
  );

  if (!res.ok) {
    // A failed reply must never fail the order it describes.
    console.error("whatsapp send failed", res.status, await res.text().catch(() => ""));
  }
}

export function sendText(to: string, body: string): Promise<void> {
  return send({ to, type: "text", text: { preview_url: true, body } });
}

/** Message with a single URL button — used for the Square checkout link. */
export function sendPayLink(to: string, body: string, url: string): Promise<void> {
  return send({
    to,
    type: "interactive",
    interactive: {
      type: "cta_url",
      body: { text: body },
      action: { name: "cta_url", parameters: { display_text: "Pay now", url } },
    },
  });
}

/** Opens the order Flow from a chat message. */
export function sendFlowPrompt(to: string, body: string): Promise<void> {
  return send({
    to,
    type: "interactive",
    interactive: {
      type: "flow",
      body: { text: body },
      action: {
        name: "flow",
        parameters: {
          flow_message_version: "3",
          flow_id: requireEnv("WHATSAPP_FLOW_ID"),
          flow_cta: "Start your order",
          // No data endpoint: the Flow is published with the menu baked in and
          // regenerated by scripts/whatsapp-flow-publish.mjs when prices change.
          mode: "published",
          flow_action: "navigate",
          flow_token: crypto.randomUUID(),
        },
      },
    },
  });
}

/**
 * Meta signs each webhook with the app secret over the raw body. Verified in
 * constant time — a fast reject leaks how much of the digest matched.
 */
export async function isValidSignature(rawBody: string, header: string | null): Promise<boolean> {
  if (!header?.startsWith("sha256=")) return false;
  const expectedHex = header.slice("sha256=".length);

  const key = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(requireEnv("WHATSAPP_APP_SECRET")),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"],
  );
  const mac = await crypto.subtle.sign("HMAC", key, new TextEncoder().encode(rawBody));
  const actualHex = [...new Uint8Array(mac)].map((b) => b.toString(16).padStart(2, "0")).join("");

  if (actualHex.length !== expectedHex.length) return false;
  let diff = 0;
  for (let i = 0; i < actualHex.length; i++)
    diff |= actualHex.charCodeAt(i) ^ expectedHex.charCodeAt(i);
  return diff === 0;
}
